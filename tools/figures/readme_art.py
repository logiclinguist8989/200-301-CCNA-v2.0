def domain_strip():
    """The five CCNA v2.0 domains with their chapter ranges."""
    c = Canvas(1160, 330, None, "Five exam domains, 28 chapters, one campus network",
               "Each chapter adds to the same Packet Tracer campus, so the network grows with you from Lab 1.1 to the capstone",
               badge="CCNA v2.0")
    doms = [("1", "Infrastructure & Connectivity", "25 % · Ch. 1–4, 14, 16–17", "router", "blue"),
            ("2", "Switching & Network Access", "25 % · Ch. 5–9, 15", "switch", "green"),
            ("3", "IP Routing", "20 % · Ch. 10–13", "l3switch", "amber"),
            ("4", "Network Services & Security", "20 % · Ch. 18–24", "firewall", "purple"),
            ("5", "AI, Operations & Management", "10 % · Ch. 25–27", "robot", "red")]
    w = 208
    for i, (n, t, ch, icon, col) in enumerate(doms):
        x = 40 + i * (w + 10)
        F = fam(col)
        c.rect(x, 110, w, 180, fill=F[1], stroke=F[0], r=14, sw=1.8, shadow=True)
        c.badge(x + 24, 134, n, col, r=13, size=12.5)
        c.device(icon, x + w / 2, 186, None, s=0.85)
        c.text(x + w / 2, 248, t, 13, F[2], 800, "middle")
        c.text(x + w / 2, 270, ch, 11.5, MUTED, 600, "middle")
    return c


ART = {"how-this-guide-was-made": how_it_was_made, "ccna-domains": domain_strip}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in ART.items():
        path = OUT / f"{name}.svg"
        path.write_text(fn().svg(), encoding="utf-8")
        print(f"README art  ->  {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
